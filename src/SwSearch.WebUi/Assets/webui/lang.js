window.SW_T = function (language, key) {
  const table = window.SW_STRINGS[language];
  if (table && Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  const fallback = window.SW_STRINGS[window.SW_DEFAULT_LANG];
  return (fallback && Object.prototype.hasOwnProperty.call(fallback, key)) ? fallback[key] : key;
};

window.SW_FORMAT = function (template) {
  let result = String(template);
  for (let index = 1; index < arguments.length; index++) {
    result = result.split("{" + (index - 1) + "}").join(String(arguments[index]));
  }
  return result;
};
