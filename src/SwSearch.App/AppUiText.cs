    public static string Get(string language, string key)
    {
        if (Tables.TryGetValue(language, out var table) && table.TryGetValue(key, out var value))
        {
            return value;
        }
        return Chinese.TryGetValue(key, out var fallback) ? fallback : key;
    }

    public static string F(string language, string key, params object?[] args)
    {
        var format = Get(language, key);
        return args.Length == 0 ? format : string.Format(CultureInfo.CurrentCulture, format, args);
    }

